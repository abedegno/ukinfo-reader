CREATE TABLE IF NOT EXISTS datasets (
    id smallint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    key text NOT NULL UNIQUE,
    manifest jsonb NOT NULL,
    entries bigint NOT NULL,
    stats jsonb NOT NULL DEFAULT '{}',
    imported_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS terms (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key text COLLATE "C" NOT NULL UNIQUE
);
INSERT INTO terms(id,key) VALUES (0,'') ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS entries (
    id integer NOT NULL,
    dataset_id smallint NOT NULL,
    kind smallint NOT NULL CHECK (kind IN (0,1)),
    name_id integer NOT NULL,
    first_id integer NOT NULL,
    postcode_id integer NOT NULL,
    PRIMARY KEY(dataset_id,id)
) PARTITION BY LIST(dataset_id);
CREATE INDEX IF NOT EXISTS entries_name ON entries
    (dataset_id,kind,name_id,first_id,id);
CREATE INDEX IF NOT EXISTS entries_postcode ON entries
    (dataset_id,kind,postcode_id,name_id,first_id,id);
CREATE TABLE IF NOT EXISTS record_blocks (
    dataset_id smallint NOT NULL,
    id integer NOT NULL,
    payload bytea NOT NULL,
    PRIMARY KEY(dataset_id,id)
) PARTITION BY LIST(dataset_id);
